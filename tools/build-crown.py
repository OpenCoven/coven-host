"""Bake the hero mesh with blender -b --factory-startup --python tools/build-crown.py."""

import base64
from pathlib import Path
import re
import struct
import xml.etree.ElementTree as ET

import bpy

ASSETS = Path(__file__).resolve().parents[1] / "docs/assets"
profile = ET.parse(ASSETS / "crown.svg").find("{http://www.w3.org/2000/svg}path")
tokens = iter(re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", profile.attrib["d"]))


def point():
    x, y = float(next(tokens)), float(next(tokens))
    return ((x - 1024) / 635, (1024 - y) / 635, 0)


curve = bpy.data.curves.new("OpenCoven crown", "CURVE")
curve.dimensions = "2D"
curve.fill_mode = "BOTH"
curve.resolution_u = 10
curve.extrude = 0.11
curve.bevel_depth = 0.026
curve.bevel_resolution = 4

for command in tokens:
    if command == "M":
        spline = curve.splines.new("BEZIER")
        spline.use_cyclic_u = True
        spline.use_smooth = True
        tip = spline.bezier_points[0]
        first = point()
        tip.co = tip.handle_left = tip.handle_right = first
    elif command in ("L", "C"):
        if command == "C":
            tip.handle_right = point()
            incoming = point()
        end = point()
        if end == first:
            tip = spline.bezier_points[0]
        else:
            spline.bezier_points.add(1)
            tip = spline.bezier_points[-1]
            tip.co = tip.handle_left = tip.handle_right = end
        if command == "C":
            tip.handle_left = incoming
    elif command != "Z":
        raise ValueError(f"Unsupported SVG command {command}")

obj = bpy.data.objects.new("Crown", curve)
bpy.context.collection.objects.link(obj)
mesh = obj.evaluated_get(bpy.context.evaluated_depsgraph_get()).to_mesh()
mesh.calc_loop_triangles()
vertices, indices = {}, []
for triangle in mesh.loop_triangles:
    for corner in triangle.loops:
        co = mesh.vertices[mesh.loops[corner].vertex_index].co
        normal = mesh.corner_normals[corner].vector
        vertex = tuple(round(v * 16384) for v in co) + tuple(round(v * 32767) for v in normal)
        if vertex not in vertices:
            vertices[vertex] = len(vertices)
        indices.append(vertices[vertex])
assert len(vertices) < 65536
geometry = b"".join(struct.pack("<6h", *v) for v in vertices)
geometry += struct.pack(f"<{len(indices)}H", *indices)
encoded = base64.b64encode(geometry).decode("ascii")
# A classic script works when the page is opened from disk, including offline.
(ASSETS / "crown-mesh.js").write_text(
    "// Generated by tools/build-crown.py from crown.svg. Positions, normals, then triangle indices.\n"
    f"const crownMesh = {{ vertices: {len(vertices)}, data: '{encoded}' }};\n"
)
print(f"Crown: {len(vertices)} vertices, {len(indices) // 3} triangles, {len(geometry)} bytes")
